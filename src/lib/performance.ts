/** Only explicitly quantified, unambiguous p95/error/throughput phrases are interpreted. */
export function criteriaFromRequirements(reqs: RequirementEvidence[]): { criteria: Criterion[]; notes: string[] } {
  const found: Criterion[] = [];
  const notes: string[] = [];
  for (const req of reqs) {
    const source = `${req.docName} / ${req.reqKey} (${req.id})`;
    const text = [req.text, ...req.acceptance].join("\n");
    const p95 = [...text.matchAll(/\b(?:p95|95th percentile)\s*(?:latency|response time)?\s*(?:≤|<=|under|below|at most|within)\s*(\d+(?:\.\d+)?)\s*(ms|milliseconds?|s|seconds?)\b/gi)];
    const errors = [...text.matchAll(/\b(?:error|failure) rate\s*(?:≤|<=|under|below|at most)\s*(\d+(?:\.\d+)?)\s*%/gi)];
    const throughput = [...text.matchAll(/\b(?:throughput|request rate)\s*(?:≥|>=|at least)\s*(\d+(?:\.\d+)?)\s*(?:rps|req(?:uests?)?\/s|requests? per second)\b/gi)];
    for (const match of p95) found.push({ metric: "p95Ms", limit: Number(match[1]) * (/^s/i.test(match[2]) ? 1000 : 1), source, implicit: false });
    for (const match of errors) found.push({ metric: "errorPercent", limit: Number(match[1]), source, implicit: false });
    for (const match of throughput) found.push({ metric: "throughputRps", limit: Number(match[1]), source, implicit: false });
    if (/\b(performance|latency|response time|throughput|error rate|within \d+ seconds?)\b/i.test(text) && !p95.length && !errors.length && !throughput.length) {
      notes.push(`${source}: performance wording has no supported quantified SLA; needs review.`);
    }
  }
  const criteria: Criterion[] = [];
  for (const metric of ["p95Ms", "errorPercent", "throughputRps"] as const) {
    const matches = found.filter((c) => c.metric === metric);
    if (new Set(matches.map((c) => c.limit)).size > 1) notes.push(`Conflicting ${metric} thresholds across linked requirements; needs review.`);
    else if (matches.length) criteria.push(...matches);
    else if (metric !== "throughputRps") criteria.push({ metric, limit: metric === "p95Ms" ? 1000 : 1, source: "RASQ-Ai implicit default", implicit: true });
    else notes.push("No throughput SLA in linked requirements; needs review (observed throughput is reported without a pass threshold).");
  }
  if (!reqs.length) notes.push("No linked requirement documents selected; needs review.");
  return { criteria, notes };
}

export type Sample = { timeStamp: number; elapsed: number; success: boolean };
export function parseJtl(csv: string): Sample[] {
  const lines = csv.trim().split(/\r?\n/);
  const columns = lines.shift()?.split(",") ?? [];
  const indexes = ["timeStamp", "elapsed", "success"].map((c) => columns.indexOf(c));
  if (indexes.some((i) => i < 0)) throw new Error("JMeter result lacks required CSV fields.");
  if (lines.length > 100_000) throw new Error("JMeter result exceeds the sample limit.");
  return lines.map((line) => {
    const values = line.split(",");
    const timeStamp = Number(values[indexes[0]]);
    const elapsed = Number(values[indexes[1]]);
    const success = values[indexes[2]];
    if (!Number.isFinite(timeStamp) || timeStamp < 0 || !Number.isFinite(elapsed) || elapsed < 0 || !["true", "false"].includes(success)) throw new Error("Malformed JMeter sample.");
    return { timeStamp, elapsed, success: success === "true" };
  });
}

// One-sided 95% Wilson bounds, assuming independent samples; not a field measurement.
function wilson(successes: number, n: number, upper: boolean): number {
  const z = 1.645;
  const p = successes / n;
  return (p + z * z / (2 * n) + (upper ? 1 : -1) * z * Math.sqrt((p * (1 - p) + z * z / (4 * n)) / n)) / (1 + z * z / n);
}
export function analyze(samples: Sample[], plan: PerformancePlan, reqs: RequirementEvidence[]): { status: "failed" | "needs-review" | "passed"; summary: PerformanceSummary } {
  if (!samples.length) throw new Error("JMeter produced no samples.");
  const sorted = samples.map((s) => s.elapsed).sort((a, b) => a - b);
  const p95Ms = sorted[Math.ceil(sorted.length * .95) - 1];
  const errors = samples.filter((s) => !s.success).length;
  const errorPercent = errors * 100 / samples.length;
  const windowMs = Math.max(...samples.map((s) => s.timeStamp + s.elapsed)) - Math.min(...samples.map((s) => s.timeStamp));
  const throughputRps = samples.length / Math.max(windowMs / 1000, 1);
  const { criteria, notes } = criteriaFromRequirements(reqs);
  const decisions: PerformanceSummary["decisions"] = [];
  for (const c of criteria) {
    if (c.metric === "p95Ms") {
      const within = samples.filter((s) => s.elapsed <= c.limit).length;
      decisions.push({ metric: c.metric, status: p95Ms > c.limit ? "failed" : wilson(within, samples.length, false) >= .95 ? "passed" : "needs-review", message: `p95 ${p95Ms} ms vs ≤ ${c.limit} ms; one-sided 95% lower bound for in-budget fraction: ${(wilson(within, samples.length, false) * 100).toFixed(2)}% (${c.source}).` });
    } else if (c.metric === "errorPercent") {
      decisions.push({ metric: c.metric, status: errorPercent > c.limit ? "failed" : wilson(errors, samples.length, true) * 100 <= c.limit ? "passed" : "needs-review", message: `Errors ${errors}/${samples.length} (${errorPercent.toFixed(2)}%) vs ≤ ${c.limit}%; one-sided 95% upper bound: ${(wilson(errors, samples.length, true) * 100).toFixed(2)}% (${c.source}).` });
    } else {
      decisions.push({ metric: c.metric, status: throughputRps < c.limit ? "failed" : "needs-review", message: `Observed throughput ${throughputRps.toFixed(2)} req/s vs ≥ ${c.limit} req/s (${c.source}); no confidence bound on throughput.` });
    }
  }
  const summary: PerformanceSummary = { count: samples.length, errors, p95Ms, errorPercent, throughputRps, criteria, decisions, notes, planSnapshot: plan, requirementSnapshot: reqs.map(({ id, reqKey, docId, docName }) => ({ id, reqKey, docId, docName })) };
  const status = decisions.some((d) => d.status === "failed") ? "failed" : notes.length || decisions.some((d) => d.status === "needs-review") ? "needs-review" : "passed";
  return { status, summary };
}
