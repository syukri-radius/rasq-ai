import { z } from "zod";

// Deliberately one independent JSON REST sampler: no arbitrary JMX, scripts, auth,
// redirects, cookies, extractors or dependent requests (thus no session correlation).
export const PerformancePlanSchema = z.object({
  name: z.string().trim().min(1).max(100),
  method: z.enum(["GET", "POST", "PUT", "PATCH", "DELETE"]),
  url: z.string().max(500),
  jsonBody: z.string().max(2048).default(""),
  threads: z.number().int().min(1).max(10).default(2),
  rampUpSeconds: z.number().int().min(1).max(30).default(2),
  durationSeconds: z.number().int().min(5).max(60).default(20),
  thinkTimeMs: z.number().int().min(300).max(5000).default(500),
  requirementIds: z.array(z.string().uuid()).max(50).default([]),
}).strict().superRefine((plan, ctx) => {
  if (plan.method === "GET" || plan.method === "DELETE") {
    if (plan.jsonBody.trim()) ctx.addIssue({ code: "custom", message: "GET and DELETE plans cannot contain a body." });
  } else {
    try {
      const body: unknown = JSON.parse(plan.jsonBody);
      if (!body || typeof body !== "object" || Array.isArray(body)) throw new Error();
      if (/"(?:password|passwd|secret|token|api[_-]?key|authorization|cookie|card(?:number)?)"\s*:/i.test(plan.jsonBody)) throw new Error();
    } catch { ctx.addIssue({ code: "custom", message: "Supply a JSON object containing synthetic data only; credential fields are forbidden." }); }
  }
});
export type PerformancePlan = z.infer<typeof PerformancePlanSchema>;
export type RequirementEvidence = { id: string; reqKey: string; docId: string; docName: string; text: string; acceptance: string[] };
export type Criterion = { metric: "p95Ms" | "errorPercent" | "throughputRps"; limit: number; source: string; implicit: boolean };
export type PerformanceSummary = {
  count: number; errors: number; p95Ms: number; errorPercent: number; throughputRps: number;
  criteria: Criterion[]; decisions: { metric: Criterion["metric"]; status: "passed" | "failed" | "needs-review"; message: string }[];
  notes: string[]; requirementSnapshot: { id: string; reqKey: string; docId: string; docName: string }[];
  planSnapshot: PerformancePlan;
};

export function checkTarget(value: string, origins: string[]): URL {
  const url = new URL(value);
  if (!["http:", "https:"].includes(url.protocol) || url.username || url.password || url.search || url.hash || !url.hostname || !origins.includes(url.origin)) {
    throw new Error("Target must be an explicitly allowed HTTP(S) origin without credentials, query or fragment.");
  }
  return url;
}

